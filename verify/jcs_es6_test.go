package verify

import "testing"

// TestJCSNumbersMatchES6 pins jcsWriteNumber to ES6 Number.toString(), which
// RFC 8785 section 3.2.2.3 defers to. Expected values were generated with node.
func TestJCSNumbersMatchES6(t *testing.T) {
	cases := []struct{ in, want string }{
		{"0", "0"},
		{"1", "1"},
		{"-1", "-1"},
		{"1.5", "1.5"},
		{"-1.5", "-1.5"},
		{"0.5", "0.5"},
		{"0.1", "0.1"},
		{"2.5", "2.5"},
		{"1e-7", "1e-7"},
		{"5e-7", "5e-7"},
		{"9.9e-7", "9.9e-7"},
		{"1e-6", "0.000001"},
		{"1.5e-6", "0.0000015"},
		{"1e-5", "0.00001"},
		{"0.000123", "0.000123"},
		{"9223372036854775807", "9223372036854776000"},
		{"9.3e18", "9300000000000000000"},
		{"1e19", "10000000000000000000"},
		{"1.5e20", "150000000000000000000"},
		{"1.2345e20", "123450000000000000000"},
		{"9.999e20", "999900000000000000000"},
		{"1e20", "100000000000000000000"},
		{"9.9e20", "990000000000000000000"},
		{"1e21", "1e+21"},
		{"1.5e21", "1.5e+21"},
		{"1e22", "1e+22"},
		{"-1.5e20", "-150000000000000000000"},
		{"-1e21", "-1e+21"},
		{"3.141592653589793", "3.141592653589793"},
		{"1e100", "1e+100"},
		{"5e-324", "5e-324"},
		{"1.7976931348623157e308", "1.7976931348623157e+308"},
		{"123456789", "123456789"},
		{"0.30000000000000004", "0.30000000000000004"},
	}
	bad := 0
	for _, c := range cases {
		got, err := JCSCanonicalize([]byte(`{"a":` + c.in + `}`))
		if err != nil {
			t.Errorf("%-24s error: %v", c.in, err)
			bad++
			continue
		}
		want := `{"a":` + c.want + `}`
		if string(got) != want {
			t.Errorf("XX %-24s got %s  want %s", c.in, got, want)
			bad++
			continue
		}
	}
	t.Logf("%d/%d 通过", len(cases)-bad, len(cases))
}
